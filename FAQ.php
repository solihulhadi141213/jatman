    <li>
      <strong>Apa itu JATMAN?</strong>
      <p>
        JATMAN adalah singkatan dari <em>Jam’iyyah Ahlith Thariqah al-Mu’tabarah an-Nahdliyyah</em>,
        yaitu organisasi yang menaungi thariqah-thariqah mu’tabarah (thariqah yang memiliki sanad jelas
        hingga Rasulullah ﷺ). Organisasi ini berada di bawah naungan Nahdlatul Ulama (NU) dan berperan
        menjaga, mengembangkan, serta menguatkan ajaran tasawuf amali yang sesuai dengan syariat Islam.
      </p>
    </li>

    <li>
      <strong>Apa tujuan utama JATMAN Jawa Barat?</strong>
      <p>Tujuan utama JATMAN Jawa Barat adalah:</p>
      <ul>
        <li>Menjaga kemurnian ajaran thariqah mu’tabarah.</li>
        <li>Menjadi wadah persaudaraan antar mursyid, ikhwan thariqah, dan masyarakat pecinta tasawuf.</li>
        <li>Membimbing umat agar tetap berjalan di jalan syariat, thariqah, hakikat, dan ma’rifat secara seimbang.</li>
        <li>Menguatkan ukhuwah Islamiyah, ukhuwah wathoniyah, dan ukhuwah insaniyah di Jawa Barat.</li>
      </ul>
    </li>

    <li>
      <strong>Apa manfaat adanya website JATMAN Jawa Barat?</strong>
      <p>Website ini dibuat untuk memberikan manfaat bagi jamaah dan masyarakat luas, antara lain:</p>
      <ul>
        <li>Menjadi pusat informasi resmi tentang kegiatan JATMAN Jawa Barat.</li>
        <li>Memudahkan komunikasi dan koordinasi antar pengurus, mursyid, dan jamaah.</li>
        <li>Menyediakan kajian, artikel, dan materi keislaman seputar tasawuf dan thariqah.</li>
        <li>Menjadi sarana dakwah digital agar nilai-nilai tasawuf dapat tersampaikan lebih luas.</li>
        <li>Memberikan layanan informasi bagi masyarakat yang ingin mengenal lebih dekat thariqah mu’tabarah.</li>
      </ul>
    </li>

    <li>
      <strong>Siapa saja yang bisa bergabung dengan JATMAN?</strong>
      <p>
        Siapa pun umat Islam yang memiliki keinginan untuk mendalami tasawuf melalui thariqah mu’tabarah dapat bergabung
        dengan bimbingan mursyid yang sah. Website ini juga terbuka bagi masyarakat umum yang ingin mendapatkan informasi
        seputar thariqah.
      </p>
    </li>

    <li>
      <strong>Bagaimana cara mengetahui kegiatan JATMAN Jawa Barat?</strong>
      <p>
        Informasi kegiatan seperti haul, manaqiban, pengajian, musyawarah, dan pelatihan akan diumumkan secara berkala
        melalui website dan media sosial resmi JATMAN Jawa Barat.
      </p>
    </li>

    <li>
      <strong>Apakah website ini bisa menjadi sarana belajar tasawuf?</strong>
      <p>
        Ya, melalui artikel, kajian online, dan informasi kegiatan, website ini diharapkan dapat memperluas pemahaman masyarakat
        tentang tasawuf dan thariqah secara benar dan sesuai tuntunan syariat.
      </p>
    </li>

    <li>
      <strong>Bagaimana cara menghubungi JATMAN Jawa Barat?</strong>
      <p>
        Website menyediakan halaman <strong>Kontak</strong> yang dapat digunakan untuk mengirim pertanyaan, saran, atau permintaan informasi.
        Jamaah juga dapat menghubungi pengurus wilayah melalui nomor dan email resmi yang tertera di sana.
      </p>
    </li>

    <li>
      <strong>Mengapa JATMAN perlu hadir di dunia digital?</strong>
      <p>
        Karena dakwah dan pembinaan umat tidak lagi terbatas pada pertemuan fisik. Dengan hadir di dunia digital, JATMAN Jawa Barat
        dapat menjangkau jamaah dan masyarakat lebih luas, termasuk generasi muda yang aktif di media online, sehingga nilai-nilai
        thariqah mu’tabarah tetap relevan di era modern.
      </p>
    </li>
  </ol>
